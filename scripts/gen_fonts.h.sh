#!/bin/sh
# Generates src/fonts.h from every .woff2 file in html/src/style/.
set -eu

DIR="$(dirname "$0")/.."
FONT_DIR="${1:-$DIR/html/src/style}"
OUT="${2:-$DIR/src/fonts.h}"

ls -l "$FONT_DIR"/*.woff2

{
echo '/* Auto-generated by scripts/gen_fonts.sh. Do not edit. */'
echo '#ifndef FONTS_H'
echo '#define FONTS_H'
echo
echo 'typedef struct embedded_font {'
echo '  const char    *path;'
echo '  unsigned char *data;'
echo '  unsigned int  *len;'
echo '} embedded_font_t;'
echo

for f in "$FONT_DIR"/*.woff2; do
	[ -f "$f" ] || continue
	xxd -i -n "$(basename "$f")" "$f"
	echo
done

echo 'embedded_font_t embedded_fonts[] = {'
for f in "$FONT_DIR"/*.woff2; do
	[ -f "$f" ] || continue
	base=$(basename "$f")
	id=$(echo "$base" | sed 's/[^A-Za-z0-9]/_/g')
	echo "  { \"/${base}\", ${id}, &${id}_len },"
done
echo '  { NULL, NULL, NULL }'
echo '};'
echo
echo '#endif'
} > "$OUT"

ls -l "$OUT"
